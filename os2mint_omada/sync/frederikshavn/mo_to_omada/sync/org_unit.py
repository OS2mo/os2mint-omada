from uuid import UUID

import structlog

from os2mint_omada.autogenerated_graphql_client import GraphQLClient
from os2mint_omada.sync.frederikshavn.mo_to_omada.mo.org_unit import (
    get_org_unit as get_mo_org_unit,
)
from os2mint_omada.sync.frederikshavn.mo_to_omada.models import MOOrgUnit
from os2mint_omada.sync.frederikshavn.mo_to_omada.models import OmadaOrgUnit
from os2mint_omada.sync.frederikshavn.mo_to_omada.omada.client import OmadaClient
from os2mint_omada.sync.frederikshavn.mo_to_omada.omada.org_unit import create_org_unit
from os2mint_omada.sync.frederikshavn.mo_to_omada.omada.org_unit import delete_org_unit
from os2mint_omada.sync.frederikshavn.mo_to_omada.omada.org_unit import (
    get_org_unit as get_omada_org_unit,
)
from os2mint_omada.sync.frederikshavn.mo_to_omada.omada.org_unit import update_org_unit

logger = structlog.stdlib.get_logger()


def _is_up_to_date(mo_org_unit: MOOrgUnit, omada_org_unit: OmadaOrgUnit) -> bool:
    """Whether the Omada org unit attributes match MO."""
    return (
        omada_org_unit.ouid == mo_org_unit.user_key
        and omada_org_unit.name == mo_org_unit.name
        and omada_org_unit.parent_uid == mo_org_unit.parent
        and omada_org_unit.c_departmenttype == mo_org_unit.org_unit_type
    )


async def sync_ou(
    graphql_client: GraphQLClient,
    omada_client: OmadaClient,
    org_unit_uuid: UUID,
) -> None:
    """
    Synchronise an org unit from MO to Omada.

    The Omada org unit is identified by its UId, which is the UUID of the MO
    org unit.

    * Exists in MO but not in Omada: create it in Omada.
    * Exists in both: update the Omada org unit if it differs from MO.
    * Does not exist in MO (anymore), or has expired in MO, but exists in
      Omada: delete it in Omada.

    Args:
        graphql_client: the MO GraphQLClient
        omada_client: the Omada client
        org_unit_uuid: UUID of the MO org unit
    """
    log = logger.bind(org_unit_uuid=org_unit_uuid)

    # Get units in MO and Omada
    mo_org_unit = await get_mo_org_unit(graphql_client, org_unit_uuid)
    omada_org_unit = await get_omada_org_unit(omada_client, org_unit_uuid)

    if mo_org_unit is None:
        # Happens when unit not exist in MO, or has expired in MO
        if omada_org_unit is None:
            log.info("Org unit exists in neither MO nor Omada: nothing to do")
            return
        log.info("Org unit does not exist in MO: deleting it in Omada")
        await delete_org_unit(omada_client, omada_org_unit)
        return

    if omada_org_unit is None:
        log.info("Org unit does not exist in Omada: creating it")
        await create_org_unit(omada_client, org_unit_uuid, mo_org_unit)
        return

    if _is_up_to_date(mo_org_unit, omada_org_unit):
        log.info("Omada org unit is up to date")
        return
    log.info("Omada org unit differs from MO: updating it")
    await update_org_unit(omada_client, mo_org_unit, omada_org_unit)
