from datetime import datetime
from uuid import UUID

from more_itertools import first
from more_itertools import one

from os2mint_omada.autogenerated_graphql_client import GraphQLClient
from os2mint_omada.autogenerated_graphql_client import OrganisationUnitFilter
from os2mint_omada.sync.frederikshavn.mo_to_omada.models import MOOrgUnit
from os2mint_omada.util import MO_TZ


async def get_org_unit(gql_client: GraphQLClient, uuid: UUID) -> MOOrgUnit | None:
    """
    Get the current MO org unit data or the first future validity data, if the
    unit only exists in the future.

    Args:
         gql_client: the MO GraphQLClient
         uuid: UUID of the MO org unit

    Returns:
        The current or future org unit data if available or None otherwise.
    """
    org_unit = await gql_client.get_org_unit(
        OrganisationUnitFilter(
            uuids=[uuid],
            from_date=datetime.now(tz=MO_TZ),
            to_date=None,
        )
    )
    if not org_unit.objects:
        return None

    validity = first(one(org_unit.objects).validities)

    unit_type = validity.unit_type_response
    assert unit_type is not None

    return MOOrgUnit(
        user_key=validity.user_key,
        name=validity.name,
        parent=validity.parent_uuid,
        org_unit_type=first(unit_type.validities).name,
    )
